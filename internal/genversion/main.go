// Command genversion writes gateway/version_gen.go, holding the spec's
// info.version as the GeneratedFromVersion constant.
//
// Invoked via go:generate alongside oapi-codegen; see gateway/gateway.go.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

func main() {
	spec := flag.String("spec", "", "path to OpenAPI JSON spec")
	out := flag.String("out", "version_gen.go", "output file (package gateway)")
	flag.Parse()

	raw, err := os.ReadFile(*spec)
	if err != nil {
		log.Fatal(err)
	}
	var doc struct {
		Info struct {
			Version string `json:"version"`
		} `json:"info"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		log.Fatal(err)
	}
	version := strings.TrimSpace(doc.Info.Version)
	if version == "" {
		log.Fatalf("%s: info.version is empty", *spec)
	}

	src := fmt.Sprintf(`// Code generated by internal/genversion; DO NOT EDIT.
// Regenerate with: go generate ./...

package gateway

// GeneratedFromVersion is the Airlock Gateway release this client was
// generated from; Connect compares it against the connected gateway.
const GeneratedFromVersion = %q
`, version)

	formatted, err := format.Source([]byte(src))
	if err != nil {
		log.Fatalf("generated source is not valid Go: %v", err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("generated %s (gateway version %s)\n", *out, version)
}
